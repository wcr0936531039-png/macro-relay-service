import assert from 'node:assert/strict';
import {attachUSSectorContext} from './us-sector-context.js';
const report={macroGate:{status:'WATCH'},tenD:{score:78},veto:{blocked:true},score:78};
const original=JSON.stringify(report);
const unknown=await attachUSSectorContext(report,async()=>({ok:false,status:503}),new Date('2026-10-14T12:00:00Z'));
assert.equal(JSON.stringify(report),original);
assert.notEqual(unknown,report);
assert.deepEqual(unknown.macroGate,report.macroGate);
assert.deepEqual(unknown.tenD,report.tenD);
assert.deepEqual(unknown.veto,report.veto);
assert.equal(unknown.score,78);
assert.equal(unknown.usSectorContext.status,'UNKNOWN');
assert.equal(unknown.usSectorContext.errorCode,'DATA_UNAVAILABLE');
assert.equal(unknown.usSectorContext.scoreContribution,0);
assert.equal(unknown.usSectorContext.vetoOverride,null);
const tickers=['SPY','XLK','XLC','XLY','XLP','XLF','XLI','XLV','XLE','XLB','XLU','XLRE'];
const rows=Array.from({length:21},(_,i)=>({date:new Date(Date.UTC(2026,8,23+i)).toISOString().slice(0,10),close:100+i}));
const complete={schema_version:1,source:'fixture',histories:Object.fromEntries(tickers.map(t=>[t,rows])),status:Object.fromEntries(tickers.map(t=>[t,{status:'ok',observed_at:'2026-10-13'}]))};
const ok=await attachUSSectorContext(report,async()=>({ok:true,json:async()=>complete}),new Date('2026-10-14T12:00:00Z'));
assert.equal(ok.usSectorContext.status,'OK');
assert.equal(ok.usSectorContext.coverage.valid,11);
assert.equal(ok.score,78);
assert.equal(ok.veto.blocked,true);
assert.equal(JSON.stringify(report),original);
await assert.rejects(()=>attachUSSectorContext(null),/REPORT_REQUIRED/);
console.log('US sector context non-mutating report integration passed');
