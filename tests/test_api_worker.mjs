import assert from 'node:assert/strict';
import {handle} from '../api-worker/index.mjs';
const now=Date.parse('2026-09-27T12:00:00Z');
const snapshot={schema_version:1,generated_at:'2026-09-27T06:00:00Z',indicators:{ON_RRP:{value:0,date:'2026-09-25',status:'ok'}}};
let reads=0;
const env={SNAPSHOT_READ_TOKEN:'test-only',MACRO_KV:{get:async()=>{reads++;return snapshot;}}};
const request=(token='test-only')=>new Request('https://example.com/api/market-snapshot',{headers:{Authorization:`Bearer ${token}`}});
globalThis.fetch=()=>{throw new Error('Unexpected external fetch');};
assert.equal((await handle(request('wrong'),env,now)).status,401);
assert.equal(reads,0);
assert.equal((await handle(request(),{},now)).status,503);
let response=await handle(request(),env,now); let body=await response.json();
assert.equal(body.rows.find(x=>x.id==='RRPONTSYD').value,0);
assert.equal(body.coverage.total,13); assert.equal(body.coverage.usable,1);
assert.equal(body.rows.find(x=>x.id==='DFII10').status,'missing');
body=await (await handle(request(),env,now+3*86400000)).json();
assert.equal(body.coverage.usable,0);
assert.equal(body.rows.find(x=>x.id==='RRPONTSYD').status,'stale');
assert.equal((await handle(request(),{...env,MACRO_KV:{get:async()=>null}},now)).status,503);
assert.equal((await handle(request(),{...env,MACRO_KV:{get:async()=>{throw Error('private');}}},now)).status,503);
console.log('API Worker auth, zero, missing, stale, and no-upstream checks passed');

const sectorRequest=new Request('https://example.com/api/us-sector-report');
const sectorFallback=await handle(sectorRequest,{},Date.parse('2026-10-14T12:00:00Z'),async()=>({ok:false,status:503}));
const sectorBody=await sectorFallback.json();
assert.equal(sectorFallback.status,200);
assert.equal(sectorBody.status,'UNKNOWN');
assert.equal(sectorBody.scoreContribution,0);
assert.equal(sectorBody.errorCode,'DATA_UNAVAILABLE');
assert.equal(reads,2);
assert.equal((await handle(new Request('https://example.com/api/us-sector-report',{method:'POST'}),{},now)).status,405);
console.log('US sector API isolated fallback passed');

const tickers=['SPY','XLK','XLC','XLY','XLP','XLF','XLI','XLV','XLE','XLB','XLU','XLRE'];
const rows=Array.from({length:21},(_,i)=>({date:new Date(Date.UTC(2026,8,23+i)).toISOString().slice(0,10),close:100+i}));
const complete={schema_version:1,source:'fixture',generated_at:'2026-10-13T00:00:00Z',histories:Object.fromEntries(tickers.map(t=>[t,rows])),status:Object.fromEntries(tickers.map(t=>[t,{status:'ok',observed_at:'2026-10-13'}]))};
const sectorOK=await (await handle(sectorRequest,{},Date.parse('2026-10-14T12:00:00Z'),async()=>({ok:true,json:async()=>complete}))).json();
assert.equal(sectorOK.status,'OK');
assert.equal(sectorOK.coverage.valid,11);
assert.equal(sectorOK.scoreContribution,0);
assert.equal(sectorOK.vetoOverride,null);
const sectorStale=await (await handle(sectorRequest,{},Date.parse('2026-10-20T12:00:00Z'),async()=>({ok:true,json:async()=>complete}))).json();
assert.equal(sectorStale.status,'UNKNOWN');
assert.equal(sectorStale.errorCode,'STALE_DATA');
assert.equal(sectorStale.scoreContribution,0);
console.log('US sector API complete and stale contracts passed');

