import assert from 'node:assert/strict';
import {handleStockReport} from '../api-worker/stock-report.mjs';
import {saveStockSnapshot} from '../site-contract/stock-store.mjs';
const map=new Map(),kv={get:async k=>map.get(k)??null,put:async(k,v)=>map.set(k,v)};
const env={SNAPSHOT_READ_TOKEN:'secret',MACRO_KV:kv};
const url='https://example.com/api/stock-report?ticker=8299';
const req=(u=url,token='secret')=>new Request(u,{headers:{Authorization:'Bearer '+token}});
assert.equal((await handleStockReport(req(url,'wrong'),env)).status,401);
assert.equal((await handleStockReport(req('https://example.com/api/stock-report?ticker=BAD'),env)).status,400);
assert.equal((await handleStockReport(req(),env)).status,503);
const as_of='2026-10-13T00:00:00.000Z';
await saveStockSnapshot(kv,{ticker:'8299',as_of,observations:[{ticker:'8299',metric:'close',value:200,observed_at:'2026-10-12',source:'TWSE',status:'ok'}]});
const response=await handleStockReport(req(),env,Date.parse(as_of));
assert.equal(response.status,200);
const body=await response.json();
assert.equal(body.report.ticker,'8299');
assert.equal(body.report.coverage.status,'partial');
assert.equal(body.report.final_rating,null);
assert.equal(body.is_stale,false);
assert.equal((await handleStockReport(req(),env,Date.parse('2026-10-16T00:00:00Z'))).status,200);
assert.equal((await (await handleStockReport(req(),env,Date.parse('2026-10-16T00:00:00Z'))).json()).is_stale,true);
console.log('stock-report endpoint tests passed');
